//! # Stealth Addresses Pallet
//!
//! A FRAME pallet for stealth address generation and management, enabling
//! unlinkable payments in the Chameleon Network. Stealth addresses ensure
//! that each payment goes to a unique address, preventing blockchain
//! observers from linking payments to recipients.
//!
//! ## Overview
//!
//! This pallet provides:
//! - Registration of stealth meta-addresses (spend + view key pairs)
//! - Announcement of stealth payments via ephemeral public keys
//! - Scanning functionality for recipients to find their payments
//!
//! ## Key Concepts
//!
//! - **Stealth Meta-Address**: A pair of public keys (spend pubkey + view pubkey)
//!   that allows anyone to compute a one-time stealth address for the owner.
//! - **Ephemeral Key**: A one-time public key generated by the sender and
//!   published on-chain so the recipient can find and claim the payment.
//! - **Stealth Address**: A one-time address derived from the recipient's
//!   meta-address and the sender's ephemeral key.
//!
//! ## Protocol Flow
//!
//! 1. Recipient registers their stealth meta-address (spend_pubkey, view_pubkey)
//! 2. Sender generates ephemeral keypair (r, R = r*G)
//! 3. Sender computes stealth address: P = spend_pubkey + H(r * view_pubkey) * G
//! 4. Sender publishes ephemeral pubkey R via `announce_payment`
//! 5. Recipient scans ephemeral keys and derives private key for P
//!
//! ## EIP-5564 Compatibility
//!
//! This implementation follows the stealth address standard from EIP-5564,
//! adapted for the Substrate ecosystem.

